def domain_label(domain: str) -> str:
    d = domain.lower().strip()
    if d.endswith(".co.uk"):
        return d[: -len(".co.uk")]
    if d.endswith(".com.au"):
        return d[: -len(".com.au")]
    if "." in d:
        return d.rsplit(".", 1)[0]
    return d


def _tokenize_piece(piece: str) -> list[str]:
    s = piece.lower()
    out: list[str] = []
    i = 0
    while i < len(s):
        hit = None
        for tok in _WORD_TOKENS:
            if s.startswith(tok, i):
                hit = tok
                break
        if hit:
            out.append(hit)
            i += len(hit)
            continue
        out.append(s[i:])
        break
    return out


